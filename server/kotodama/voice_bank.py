"""Reference voices for models that clone a voice from a short clip
(Chatterbox, Chatterbox Turbo, Qwen3-TTS voice_clone, ...).

The bank is a folder (default: voices/ in the addon root, not committed):

    voices/rok.wav          any WAV (or MP3/FLAC with ffmpeg), 5.5-7.5 s of clean speech
    voices/rok.json         optional: {"name", "gender", "age", "accent",
                            "description", "reference_text"}

Without a .json file, labels are guessed from the file name ("old_man_gruff"
-> male, old, gruff). Clips are converted to 16 kHz mono and trimmed to
7.5 s so they travel as small data URIs. `kotodama_server.py voices design`
fills the bank with clips generated by a voice-design model, labelled from
Kotodama's race/creature archetypes.
"""

from __future__ import annotations

import base64
import hashlib
import json
import logging
import threading
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .casting import Voice, derive_labels
from .decode import DecodeError, decode_all, wav_bytes

log = logging.getLogger("kotodama.bank")

CLIP_RATE = 16000
MAX_SECONDS = 7.5
MIN_SECONDS = 5.5            # Chatterbox Turbo needs more than 5 s
AUDIO_SUFFIXES = (".wav", ".mp3", ".flac", ".ogg")
PREFIX = "bank:"


@dataclass
class BankClip:
    id: str                  # "bank:<file stem>"
    path: Path
    voice: Voice
    wav: bytes               # normalised 16 kHz mono WAV
    sha8: str
    seconds: float
    reference_text: str | None

    @property
    def data_uri(self) -> str:
        return "data:audio/wav;base64," + base64.b64encode(self.wav).decode("ascii")

    @property
    def tag(self) -> str:
        """Stands in for the audio in cache keys: changes when the clip does."""
        return f"{self.id}:{self.sha8}"


def load_clip(path: Path) -> BankClip:
    raw = path.read_bytes()
    try:
        pcm = decode_all(raw, CLIP_RATE)
    except DecodeError as exc:
        raise ValueError(f"{path.name}: {exc}") from exc
    seconds = len(pcm) / 2 / CLIP_RATE
    if seconds < MIN_SECONDS:
        raise ValueError(f"{path.name}: {seconds:.1f} s of audio; reference clips need at least {MIN_SECONDS} s")
    trimmed = seconds > MAX_SECONDS
    if trimmed:
        pcm = pcm[:int(MAX_SECONDS * CLIP_RATE) * 2]
        seconds = MAX_SECONDS
    meta: dict[str, Any] = {}
    side = path.with_suffix(".json")
    if side.exists():
        try:
            loaded = json.loads(side.read_text(encoding="utf-8"))
            meta = loaded if isinstance(loaded, dict) else {}
        except (OSError, ValueError) as exc:
            log.warning("ignoring %s: %s", side.name, exc)
    labels = derive_labels(path.stem)
    for key in ("gender", "age", "accent", "descriptive", "use_case"):
        if meta.get(key):
            labels[key] = str(meta[key])
    wav = wav_bytes(pcm, CLIP_RATE)
    clip_id = PREFIX + path.stem
    ref_text = meta.get("reference_text") if isinstance(meta.get("reference_text"), str) else None
    voice = Voice(id=clip_id, name=str(meta.get("name") or path.stem), category="bank", labels=labels,
                  description=str(meta.get("description") or ""))
    return BankClip(id=clip_id, path=path, voice=voice, wav=wav,
                    sha8=hashlib.sha256(wav).hexdigest()[:8], seconds=seconds,
                    # A trimmed clip no longer matches its transcript.
                    reference_text=None if trimmed else ref_text)


# -- designing clips --------------------------------------------------------------

# Short enough (about 6 s) that the clip is never trimmed, so it stays a valid
# reference transcript for models that want one.
DESIGN_TEXT = "The airship to Jeuno leaves at dawn. Keep your wits about you, and mind the road through the hills."
FLAVOURS = ["", "warm and friendly", "gruff and weathered", "stern and formal", "bright and lively",
            "soft-spoken and gentle"]
_AGE_LABEL = {"child": "young", "young": "young", "adult": "middle_aged", "middle-aged": "middle_aged",
              "elderly": "old"}
_PITCH_WORDS = {"very low": "deep low", "low": "low", "high": "high bright", "very high": "high bright childlike"}
SKIP_ARCHETYPES = {"unknown"}


@dataclass
class DesignJob:
    stem: str
    archetype: str
    flavour: str
    profile: dict[str, Any]
    description: str

    def meta(self) -> dict[str, Any]:
        p = self.profile
        words = " ".join(x for x in (_PITCH_WORDS.get(str(p.get("pitch")), ""), str(p.get("tone") or ""),
                                     str(p.get("personality") or ""), self.flavour) if x)
        meta: dict[str, Any] = {
            "name": f"{self.archetype} {self.stem.rsplit('-', 1)[-1]}" + (f" ({self.flavour})" if self.flavour else ""),
            "description": self.description,
            "descriptive": " ".join(dict.fromkeys(words.replace(",", " ").split())),
            "reference_text": DESIGN_TEXT,
            "designed_from": self.archetype,
        }
        if p.get("gender") in ("male", "female"):
            meta["gender"] = p["gender"]
        if _AGE_LABEL.get(str(p.get("age"))):
            meta["age"] = _AGE_LABEL[str(p.get("age"))]
        if self.archetype == "narrator":
            meta["use_case"] = "narration"
        return meta


def design_jobs(archetypes: dict[str, dict[str, Any]], variants: int, only: list[str] | None,
                directory: Path) -> list[DesignJob]:
    """The clips `voices design` would make, skipping ones already there."""
    from .delivery import voice_description
    jobs = []
    existing = {p.stem for p in directory.iterdir()} if directory.is_dir() else set()
    for key, arch in archetypes.items():
        if key in SKIP_ARCHETYPES or (only and key not in only):
            continue
        profile = {f: arch.get(f) for f in ("gender", "age", "species", "personality", "tone", "accent",
                                            "pitch", "pace") if arch.get(f)}
        for n in range(max(1, variants)):
            stem = f"design-{key}-{n + 1}"
            if stem in existing:
                continue
            flavour = FLAVOURS[n % len(FLAVOURS)]
            jobs.append(DesignJob(stem, key, flavour, profile, voice_description(profile, flavour)))
    return jobs


def save_designed(directory: Path, job: DesignJob, audio: bytes) -> Path:
    from .decode import sniff
    kind = sniff(audio[:12])
    suffix = ".wav" if kind in ("wav", "unknown") else f".{kind}"
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / f"{job.stem}{suffix}"
    path.write_bytes(audio)
    path.with_suffix(".json").write_text(json.dumps(job.meta(), ensure_ascii=False, indent=1), encoding="utf-8")
    return path


class VoiceBank:
    def __init__(self, directory: Path):
        self.dir = Path(directory)
        self.clips: dict[str, BankClip] = {}
        self.problems: list[str] = []
        self._stamp: tuple | None = None
        self._lock = threading.Lock()

    def _signature(self) -> tuple:
        try:
            return tuple(sorted((p.name, p.stat().st_mtime_ns, p.stat().st_size)
                                for p in self.dir.iterdir() if p.suffix.lower() in AUDIO_SUFFIXES + (".json",)))
        except OSError:
            return ()

    def refresh(self) -> bool:
        """Reload when the folder changed. True if the set of clips changed."""
        sig = self._signature()
        with self._lock:
            if sig == self._stamp:
                return False
            self._stamp = sig
        clips: dict[str, BankClip] = {}
        problems: list[str] = []
        if self.dir.is_dir():
            for path in sorted(self.dir.iterdir()):
                if path.suffix.lower() not in AUDIO_SUFFIXES:
                    continue
                try:
                    clip = load_clip(path)
                    clips[clip.id] = clip
                except (OSError, ValueError) as exc:
                    problems.append(str(exc))
        for p in problems:
            log.warning("voice bank: %s", p)
        with self._lock:
            changed = set(clips) != set(self.clips) or any(clips[k].sha8 != self.clips[k].sha8 for k in clips
                                                           if k in self.clips)
            self.clips, self.problems = clips, problems
        return changed

    def voices(self) -> list[Voice]:
        with self._lock:
            return [c.voice for c in self.clips.values()]

    def get(self, voice_id: str | None) -> BankClip | None:
        if not voice_id or not voice_id.startswith(PREFIX):
            return None
        with self._lock:
            return self.clips.get(voice_id)
